"""gen_table.py > src/sqtt_table.mojo: tinygrad's RDNA3 (layout 3) SQTT decode tables as Mojo constants.
Per opcode: nibble count, delta field lo/mask, special (1 TS_DELTA_OR_MARK, 2 TS_DELTA_SHORT), kind (1 WAVESTART,
2 WAVEEND, 3 INST, 4 VALUINST, 5 IMMEDIATE, 6 IMMEDIATE_MASK, 0 other)."""
from tinygrad.renderer.amd.sqtt import (_DECODE_INFO_RDNA3, _STATE_TABLE_RDNA3, WAVESTART, WAVEEND, INST, VALUINST, IMMEDIATE, IMMEDIATE_MASK,
  TS_DELTA_OR_MARK, TS_DELTA_SHORT, TS_DELTA_S8_W3)
kind = {WAVESTART: 1, WAVEEND: 2, INST: 3, VALUINST: 4, IMMEDIATE: 5, IMMEDIATE_MASK: 6}
ops = range(max(_DECODE_INFO_RDNA3) + 1)
info = [_DECODE_INFO_RDNA3.get(o, (None, 0, 0, 0, 1, 0)) for o in ops]
row = lambda name, xs: f"comptime {name}: Array[Int, {len(xs)}] = [{', '.join(map(str, xs))}]"
print("# generated by tools/gen_table.py from tinygrad.renderer.amd.sqtt, do not edit")
print(row("STATE", list(_STATE_TABLE_RDNA3)))
# AMD's decoder (gfx10 table NEW_PC, inherited by gfx11) reads 0b0100001 as 64 bits, tinygrad as 72: the 2 extra
# nibbles desync the stream until it falls back in step, after bogus TS_DELTA_OR_MARK deltas of up to 3.7e10 cycles
nibs = lambda i: 16 if i[0] is TS_DELTA_S8_W3 else i[1]
print(row("NIBS", [nibs(i) for i in info]))
print(row("DLO", [i[2] for i in info]))
print(row("DMASK", [i[3] for i in info]))
print(row("SPECIAL", [i[5] for i in info]))
print(row("KIND", [kind.get(i[0], 0) for i in info]))
assert {TS_DELTA_OR_MARK, TS_DELTA_SHORT} <= {i[0] for i in info}
